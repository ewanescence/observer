package csod

import (
	"bytes"
	"crypto"
	"fmt"
	"strings"
	"time"

	"github.com/ProtonMail/go-crypto/openpgp"
	"github.com/ProtonMail/go-crypto/openpgp/armor"
	"github.com/ProtonMail/go-crypto/openpgp/packet"
)

// GeneratedPGPKey holds an ASCII-armored OpenPGP keypair and identifiers.
type GeneratedPGPKey struct {
	PublicKey   string    `json:"publicKey"`
	PrivateKey  string    `json:"privateKey"`
	KeyID       string    `json:"keyId"`
	Fingerprint string    `json:"fingerprint"`
	ExpiresAt   time.Time `json:"expiresAt"`
}

// GeneratePGPKeyPair creates an RSA OpenPGP keypair (2048 or 4096 bits) with an
// explicit future expiration on both the primary key and encryption subkey so
// Cornerstone's Report Encryption Keys validation accepts it as non-expired.
func GeneratePGPKeyPair(name, email, passphrase string, bits, validDays int) (GeneratedPGPKey, error) {
	name = strings.TrimSpace(name)
	if name == "" {
		name = "Observer CSOD Webhook"
	}
	email = strings.TrimSpace(email)
	if email == "" {
		email = "webhooks@observer.local"
	}
	if bits == 0 {
		bits = 4096
	}
	if bits != 2048 && bits != 4096 {
		return GeneratedPGPKey{}, fmt.Errorf("RSA key size must be 2048 or 4096 bits, got %d", bits)
	}
	if validDays <= 0 {
		validDays = 730
	}
	if validDays > 3650 {
		return GeneratedPGPKey{}, fmt.Errorf("validity must be <= 3650 days, got %d", validDays)
	}

	now := time.Now().UTC().Truncate(time.Second)
	lifetimeSecs := uint32(validDays) * 86400
	cfg := &packet.Config{
		DefaultHash:     crypto.SHA256,
		DefaultCipher:   packet.CipherAES256,
		RSABits:         bits,
		Time:            func() time.Time { return now },
		KeyLifetimeSecs: lifetimeSecs,
	}

	entity, err := openpgp.NewEntity(name, "Generated by Observer", email, cfg)
	if err != nil {
		return GeneratedPGPKey{}, fmt.Errorf("generate PGP entity: %w", err)
	}

	// openpgp.NewEntity hardcodes keyLifetimeSecs=0 on the encryption subkey.
	// Re-sign the subkey binding signature with lifetimeSecs so Cornerstone
	// sees a future expiration date on both primary and encryption subkeys.
	for i := range entity.Subkeys {
		sub := &entity.Subkeys[i]
		if sub.Sig != nil {
			sub.Sig.KeyLifetimeSecs = &lifetimeSecs
			if err := sub.Sig.SignKey(sub.PublicKey, entity.PrivateKey, cfg); err != nil {
				return GeneratedPGPKey{}, fmt.Errorf("sign encryption subkey expiration: %w", err)
			}
		}
	}

	var pubBuf bytes.Buffer
	pubW, err := armor.Encode(&pubBuf, openpgp.PublicKeyType, nil)
	if err != nil {
		return GeneratedPGPKey{}, fmt.Errorf("create public key armor writer: %w", err)
	}
	if err := entity.Serialize(pubW); err != nil {
		return GeneratedPGPKey{}, fmt.Errorf("serialize public key: %w", err)
	}
	if err := pubW.Close(); err != nil {
		return GeneratedPGPKey{}, fmt.Errorf("close public key armor writer: %w", err)
	}

	if passphrase != "" {
		passBytes := []byte(passphrase)
		if entity.PrivateKey != nil {
			if err := entity.PrivateKey.Encrypt(passBytes); err != nil {
				return GeneratedPGPKey{}, fmt.Errorf("encrypt primary private key: %w", err)
			}
		}
		for _, sub := range entity.Subkeys {
			if sub.PrivateKey != nil {
				if err := sub.PrivateKey.Encrypt(passBytes); err != nil {
					return GeneratedPGPKey{}, fmt.Errorf("encrypt subkey: %w", err)
				}
			}
		}
	}

	var privBuf bytes.Buffer
	privW, err := armor.Encode(&privBuf, openpgp.PrivateKeyType, nil)
	if err != nil {
		return GeneratedPGPKey{}, fmt.Errorf("create private key armor writer: %w", err)
	}
	if err := entity.SerializePrivate(privW, nil); err != nil {
		return GeneratedPGPKey{}, fmt.Errorf("serialize private key: %w", err)
	}
	if err := privW.Close(); err != nil {
		return GeneratedPGPKey{}, fmt.Errorf("close private key armor writer: %w", err)
	}

	return GeneratedPGPKey{
		PublicKey:   pubBuf.String(),
		PrivateKey:  privBuf.String(),
		KeyID:       entity.PrimaryKey.KeyIdString(),
		Fingerprint: fmt.Sprintf("%X", entity.PrimaryKey.Fingerprint),
		ExpiresAt:   now.Add(time.Duration(lifetimeSecs) * time.Second),
	}, nil
}
